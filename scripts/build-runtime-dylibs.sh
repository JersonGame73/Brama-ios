#!/bin/bash
# ============================================================================
# Brama iOS ARM64 Emulation Runtime Builder (libbox64 / libwine / libdxmt)
# Compiles Mach-O arm64-apple-ios17.0 dynamic libraries (.dylib) and generates
# Brama/BramaRuntimePayloads.h for automatic sandbox provisioning on iPadOS.
# ============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
SRC_DIR="$SCRIPT_DIR/runtime-src"
OUT_DIR="$PROJECT_ROOT/RuntimeDylibs"
HEADER_OUT="$PROJECT_ROOT/Brama/BramaRuntimePayloads.h"

mkdir -p "$OUT_DIR"

SDK_PATH="$(xcrun --sdk iphoneos --show-sdk-path)"
CXX="$(xcrun --sdk iphoneos --find clang++)"

echo "[BRAMA-BUILD] Using iOS SDK: $SDK_PATH"
echo "[BRAMA-BUILD] Compiling libbox64.dylib (arm64-apple-ios17.0)..."
"$CXX" -dynamiclib \
    -arch arm64 \
    -isysroot "$SDK_PATH" \
    -miphoneos-version-min=17.0 \
    -O2 -std=c++17 \
    -install_name "@rpath/libbox64.dylib" \
    "$SRC_DIR/libbox64.cpp" \
    -o "$OUT_DIR/libbox64.dylib"

echo "[BRAMA-BUILD] Compiling libwine.dylib (arm64-apple-ios17.0)..."
"$CXX" -dynamiclib \
    -arch arm64 \
    -isysroot "$SDK_PATH" \
    -miphoneos-version-min=17.0 \
    -O2 -std=c++17 \
    -install_name "@rpath/libwine.dylib" \
    "$SRC_DIR/libwine.cpp" \
    -o "$OUT_DIR/libwine.dylib"

echo "[BRAMA-BUILD] Compiling libdxmt.dylib (arm64-apple-ios17.0)..."
"$CXX" -dynamiclib \
    -arch arm64 \
    -isysroot "$SDK_PATH" \
    -miphoneos-version-min=17.0 \
    -O2 -std=c++17 \
    -install_name "@rpath/libdxmt.dylib" \
    "$SRC_DIR/libdxmt.cpp" \
    -o "$OUT_DIR/libdxmt.dylib"

# Strip & ad-hoc sign compiled Mach-O dylibs
strip -x "$OUT_DIR/libbox64.dylib" "$OUT_DIR/libwine.dylib" "$OUT_DIR/libdxmt.dylib" || true
codesign --force --sign - --timestamp=none "$OUT_DIR/libbox64.dylib" "$OUT_DIR/libwine.dylib" "$OUT_DIR/libdxmt.dylib"

echo "[BRAMA-BUILD] Generating $HEADER_OUT..."
cat << 'EOF' > "$HEADER_OUT"
//
//  BramaRuntimePayloads.h
//  Brama
//
//  Auto-generated by scripts/build-runtime-dylibs.sh
//  Contains precompiled arm64-apple-ios17.0 Mach-O dynamic libraries:
//  - libbox64.dylib
//  - libwine.dylib
//  - libdxmt.dylib
//

#pragma once
#include <cstdint>
#include <cstddef>

EOF

python3 - "$OUT_DIR" "$HEADER_OUT" << 'PYEOF'
import sys, os

out_dir = sys.argv[1]
header_out = sys.argv[2]

modules = [
    ("libbox64.dylib", "kBramaLibBox64Dylib"),
    ("libwine.dylib", "kBramaLibWineDylib"),
    ("libdxmt.dylib", "kBramaLibDxmtDylib"),
]

with open(header_out, "a") as f:
    for filename, sym in modules:
        path = os.path.join(out_dir, filename)
        data = open(path, "rb").read()
        f.write(f"static const size_t {sym}Size = {len(data)};\n")
        f.write(f"static const uint8_t {sym}Bytes[{len(data)}] = {{\n    ")
        hex_bytes = [f"0x{b:02X}" for b in data]
        for i in range(0, len(hex_bytes), 16):
            f.write(", ".join(hex_bytes[i:i+16]) + ",\n    ")
        f.write("\n};\n\n")
PYEOF

ls -lh "$OUT_DIR"
echo "[BRAMA-BUILD] Successfully built arm64-apple-ios17.0 runtime dylibs and embedded payloads!"
